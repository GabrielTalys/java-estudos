package aula03.operadores;

public class OperadoresAritmetico {
    /*
    + - Soma
    - - Subtração
    * - Multiplicação
    / - divisão
    % - resto da divisão / módulo
    ++ - incremento (ex: int x =5; --> x++, agora x = 6)
    -- - decremento (ex: int x =5; --> x--, agora x = 4)
     */
    public static void main (String[] args){
        int valor1 = 50;
        int valor2 = 10;
        System.out.println("A soma dos valores são: "+ (valor1 + valor2));
    }
}
